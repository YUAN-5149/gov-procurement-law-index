def chapter_short(ch):
    if not ch: return ''
    ch = ch.split(' › ')[-1]
    return re.sub(r'\s+', '', ch)

def cat_of_chapter(ch):
    s = chapter_short(ch)
    for k, v in CH2CAT:
        if k in s: return v
    return 'g'

def build(pcode, kind, cat=None, multi=False):
    d = P.parse(pcode)
    arts = []
    for a in d['articles']:
        ch = chapter_short(a['chapter'])
        c = cat_of_chapter(a['chapter']) if multi else cat
        rec = {'no': a['no'], 'label': a['label'], 'ch': ch, 'cat': c, 'lines': a['lines']}
        xc = EXTRA.get(pcode, {}).get(a['no'])
        if xc: rec['xc'] = [x for x in xc if x != c]
        arts.append(rec)
    return {'id': pcode, 'title': d['title'], 'short': SHORT.get(pcode, d['title']),
            'date': d['date'], 'kind': kind, 'multi': multi,
            'url': f'https://law.moj.gov.tw/LawClass/LawAll.aspx?pcode={pcode}',
            'articles': arts}

def build_pcc(fid):
    d = PCC.parse(fid)
    cat = PCCCAT[fid]
    arts = []
    for a in d['articles']:
        rec = {'no': a['no'], 'label': a['label'], 'ch': '', 'cat': cat, 'lines': a['lines']}
        if a.get('mono'): rec['mono'] = True
        arts.append(rec)
    return {'id': fid, 'title': d['title'], 'short': PCCSHORT.get(fid, d['title']),
            'date': d['date'], 'kind': ('子法' if fid == 'FL005555' else '行政規則'),
            'multi': False, 'url': f'https://lawweb.pcc.gov.tw/LawContent.aspx?id={fid}',
            'articles': arts}

